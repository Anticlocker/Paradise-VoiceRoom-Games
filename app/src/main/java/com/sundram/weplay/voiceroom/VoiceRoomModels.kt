package com.sundram.weplay.voiceroom

/**
 * Seat layout constants for the VYBORA Aurora Lounge stage.
 * Invariants:
 * - Exactly ONE Host seat (index 0).
 * - Exactly EIGHT regular numbered mic seats (indices 1 to 8, rendered in a 4x2 grid).
 * - Exactly ONE optional Partner seat (index 9, rendered to the right of the Host).
 * - Total stage capacity = 10 positions (0..9).
 */
const val HOST_SEAT_INDEX = 0
const val REGULAR_SEAT_START = 1
const val REGULAR_SEAT_END = 8
const val REGULAR_SEAT_COUNT = 8
const val PARTNER_SEAT_INDEX = 9
const val VOICE_ROOM_STAGE_CAPACITY = 10

/** Legacy alias for backwards compatibility (8 regular mic seats). */
const val VOICE_ROOM_SEAT_COUNT = 8

/**
 * Topic used for the room's text chat, carried over LiveKit reliable data packets.
 */
const val VOICE_CHAT_TOPIC = "weplay.chat"

/** Participant attributes written by [LiveKitVoiceRoomEngine] to describe seat choice. */
const val ATTR_SEAT = "wp_seat"

/** How the room is currently connected to the voice infrastructure. */
enum class RoomConnection {
    IDLE,
    CONNECTING,
    CONNECTED,
    RECONNECTING,
    FAILED,
    DISCONNECTED,
    SIMULATED,
}

enum class SeatPositionType {
    HOST,
    REGULAR,
    PARTNER,
}

enum class BondStatus {
    NONE,
    DRAFT,
    REQUESTED,
    PARTIALLY_ACCEPTED,
    ACTIVE,
    DECLINED,
    EXPIRED,
    CANCELED,
    DETACHING,
    DETACHED,
    FAILED,
}

enum class ConsentStatus {
    PENDING,
    ACCEPTED,
    DECLINED,
    REVOKED,
}

/**
 * Representation of an attached bond between two regular occupied stage seats.
 */
data class SeatBond(
    val bondId: String,
    val roomId: String,
    val firstSeat: Int,
    val secondSeat: Int,
    val firstUserId: String,
    val secondUserId: String,
    val firstConsent: ConsentStatus = ConsentStatus.PENDING,
    val secondConsent: ConsentStatus = ConsentStatus.PENDING,
    val status: BondStatus = BondStatus.REQUESTED,
    val createdAtMs: Long = System.currentTimeMillis(),
    val revision: Long = 1L,
) {
    fun canActivate(): Boolean =
        firstSeat != secondSeat &&
            firstUserId != secondUserId &&
            firstConsent == ConsentStatus.ACCEPTED &&
            secondConsent == ConsentStatus.ACCEPTED &&
            status in setOf(BondStatus.REQUESTED, BondStatus.PARTIALLY_ACCEPTED)
}

/** One voice participant occupying a seat on the stage or listening. */
data class RoomMemberVo(
    val identity: String,
    val name: String,
    /** Seat index 0..9 (Host=0, Regular=1..8, Partner=9), or null for listener. */
    val seat: Int?,
    val micOn: Boolean,
    val speaking: Boolean,
    val isSelf: Boolean,
    val joinedAtMs: Long,
    val role: String = "speaker", // "host", "partner", "moderator", "vip", "speaker", "listener"
    val avatarRes: Int? = null,
    val frameRes: Int? = null,
    val level: Int = 1,
    val isFollowed: Boolean = false,
) {
    val hasSeat: Boolean get() = seat != null && seat in 0 until VOICE_ROOM_STAGE_CAPACITY
    val isHost: Boolean get() = role == "host" || seat == HOST_SEAT_INDEX
    val isPartner: Boolean get() = role == "partner" || seat == PARTNER_SEAT_INDEX
    val isRegularSeat: Boolean get() = seat != null && seat in REGULAR_SEAT_START..REGULAR_SEAT_END
}

/** Room chat line, either typed by a participant or generated by the client. */
data class RoomMessage(
    val id: Long,
    val author: String,
    val body: String,
    val isSelf: Boolean,
    val system: Boolean = false,
    val isGift: Boolean = false,
    val giftIconRes: Int? = null,
)

/** Everything the voice-room screen renders. */
data class VoiceRoomState(
    val roomId: String = "",
    val connection: RoomConnection = RoomConnection.IDLE,
    val transportLabel: String = "",
    val members: List<RoomMemberVo> = emptyList(),
    val messages: List<RoomMessage> = emptyList(),
    val selfMicOn: Boolean = false,
    val seatCount: Int = VOICE_ROOM_STAGE_CAPACITY,
    val lockedSeats: Set<Int> = emptySet(),
    val isFavorited: Boolean = false,
    val selectedTheme: String = "aurora", // "aurora" or "celestial"
    val isEarpieceMode: Boolean = false,
    val isAudioMuted: Boolean = false,
    val partnerEnabled: Boolean = false,
    val partnerLocked: Boolean = false,
    val activeBonds: List<SeatBond> = emptyList(),
    val pendingBondConsent: SeatBond? = null,
    val error: String? = null,
) {
    /** Participants that hold a stage seat, ordered by seat index. */
    val seated: List<RoomMemberVo> =
        members.filter { it.hasSeat }.sortedBy { it.seat }

    val listenerCount: Int get() = members.count { !it.hasSeat }

    /** Returns occupant at given stage seat index (0..9). */
    fun seatAt(index: Int): RoomMemberVo? = seated.firstOrNull { it.seat == index }

    val self: RoomMemberVo? get() = members.firstOrNull { it.isSelf }

    val selfSeat: Int? get() = self?.seat

    fun isSeatLocked(seat: Int): Boolean =
        seat in lockedSeats || (seat == PARTNER_SEAT_INDEX && partnerLocked)

    fun isSeatInBond(seat: Int): Boolean =
        activeBonds.any { it.status == BondStatus.ACTIVE && (it.firstSeat == seat || it.secondSeat == seat) }

    fun getBondForSeat(seat: Int): SeatBond? =
        activeBonds.firstOrNull { it.status == BondStatus.ACTIVE && (it.firstSeat == seat || it.secondSeat == seat) }
}
