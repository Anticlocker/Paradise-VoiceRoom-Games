package com.sundram.weplay.ui.theme

import androidx.compose.ui.unit.dp

/**
 * Vybora / WePlay spacing token system.
 *
 * Use these constants instead of magic dp numbers so the
 * design system stays consistent across all composables.
 *
 *  SpaceXXS  =  2.dp  – hairline gaps, icon padding
 *  SpaceXS   =  4.dp  – tight gaps between adjacent atoms
 *  SpaceSM   =  8.dp  – component internal padding, row gaps
 *  SpaceMD   = 12.dp  – card internal padding, column gaps
 *  SpaceLG   = 16.dp  – section horizontal padding
 *  SpaceXL   = 24.dp  – between major sections
 *  SpaceXXL  = 32.dp  – generous breathing room
 *  Space3XL  = 48.dp  – top-level screen padding, hero gaps
 */
object Spacing {
    val XXS  =  2.dp
    val XS   =  4.dp
    val SM   =  8.dp
    val MD   = 12.dp
    val LG   = 16.dp
    val XL   = 24.dp
    val XXL  = 32.dp
    val XXXL = 48.dp
}

